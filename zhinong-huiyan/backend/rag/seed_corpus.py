def to_chunks() -> List[Dict]:
    """把语料转成可入库的 chunk 列表。

    每类病虫害天然构成一个知识条目，故按条目分块（不做滑窗），
    这样 chunk 与业务实体一一对应，引用时能直接回到具体病虫害。
    """
    chunks: List[Dict] = []
    for item in CORPUS:
        title = f"{item['crop']}·{item['name']}（{item['category']}）"
        lines = [
            f"症状：{item['symptoms']}",
            f"成因：{item['causes']}",
            f"预防：{'；'.join(item['prevention'])}",
            f"防治：{'；'.join(item['treatment'])}",
        ]
        chunks.append({
            "source": SOURCE_TAG,
            "ref_id": item["name"],
            "title": title,
            "text": "\n".join(lines),
            "metadata": {
                "name": item["name"],
                "crop": item["crop"],
                "category": item["category"],
                "reviewed": False,
            },
        })
    return chunks
